#!/usr/bin/env python3
"""Comic release tracker: keeps calendar/comics.json current from League of Comic Geeks.

Usage: tracker.py [--dry-run] [--ticks-file PATH] [--summary PATH] [--no-discover]

Each run:
  1. reads the calendar's ticks (jaredluyster-calendar/ticks.json in R2) and records every
     ticked comic reminder as "got" in state.json, so it never comes back (even if the
     issue is redated, which changes its tick key);
  2. fetches each followed series page listed in series.json (one request per
     CRAWL_DELAY seconds, as LOCG's robots.txt asks, with an identifying User-Agent);
  3. rewrites calendar/comics.json: one reminder per numbered issue released on or after
     first_day, not yet got. Redated issues move; issues LOCG dropped disappear. A series
     whose page can't be read keeps its previous reminders, and nothing is ever written
     from a page that looks wrong (layout change, bot check);
  4. checks each creator in series.json for series that aren't followed or ignored and
     writes them to discoveries.md for a human to decide on.
Stops fetching at the first 403/429/503: a bot check is never retried or worked around.
Exit code 1 if anything could not be fetched.
"""
import argparse, html, json, os, re, shutil, subprocess, sys, tempfile, time, urllib.error, urllib.request
from datetime import date, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CONFIG = os.path.join(HERE, "series.json")
STATE = os.path.join(HERE, "state.json")
DISCOVERIES = os.path.join(HERE, "discoveries.md")
OUT = os.path.join(ROOT, "calendar", "comics.json")
BASE = "https://leagueofcomicgeeks.com"
UA = "jaredluyster-comic-tracker/1.0 (personal release calendar; contact doctormcboop@gmail.com)"
CRAWL_DELAY = 31  # robots.txt: Crawl-delay 30
TICKS_OBJECT = "jaredluyster-calendar/ticks.json"
NOTE = ("PUBLIC FILE, like todos.json: committed to a public GitHub repo and served without a login at "
        "jaredluyster.com/calendar/comics.json. Generated by scripts/comic-tracker/tracker.py from League of "
        "Comic Geeks and the series in scripts/comic-tracker/series.json; hand edits here are overwritten on the "
        "next run. One todo per issue, on its release day, so each can be ticked off on its own. An issue drops "
        "out once it's ticked off on the calendar.")
TITLE = re.compile(r"^Comics: (.+) #(\S+) → (.+) list$")
ISSUE_TITLE = re.compile(r"^(.*?) #(\S+)$")


class Blocked(Exception):
    """LOCG refused us (403/429/503). Stop fetching for this run."""


_last_fetch = [0.0]


def fetch(path):
    wait = _last_fetch[0] + CRAWL_DELAY - time.monotonic()
    if wait > 0:
        time.sleep(wait)
    _last_fetch[0] = time.monotonic()
    req = urllib.request.Request(BASE + path, headers={"User-Agent": UA})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        if e.code in (403, 429, 503):
            raise Blocked(f"HTTP {e.code} for {path}")
        raise RuntimeError(f"HTTP {e.code} for {path}")


def parse_date(s):
    s = s.strip()
    if not s or s.upper() == "TBD":
        return None
    return datetime.strptime(re.sub(r"(\d+)(st|nd|rd|th)", r"\1", s, flags=re.I).title(), "%b %d, %Y").date()


def series_issues(path):
    """[(title, release date or None)] for the main covers on a series page."""
    page = fetch("/comics/series/" + path)
    out = []
    for chunk in page.split('<li class="issue')[1:]:
        if 'data-parent="0"' not in chunk[:300]:
            continue  # a variant cover
        t = re.search(r'data-sorting="([^"]*)"', chunk)
        d = re.search(r'class="date"[^>]*>\s*([^<]*?)\s*<', chunk)
        if t and d:
            out.append((html.unescape(t.group(1)), parse_date(d.group(1))))
    if not out:
        raise RuntimeError("no issues found on the page (layout change or bot check?)")
    return out


def creator_series(path):
    """[(series path, title, publisher, first year)] from a creator's page, newest first."""
    page = fetch("/people/" + path + "/comics")
    i = page.find('id="comic-list-titles"')
    if i < 0:
        raise RuntimeError("no series list on the creator page (layout change?)")
    out = []
    for chunk in page[i:].split("<li>")[1:]:
        link = re.search(r'href="/comics/series/(\d+/[^"]+)"', chunk)
        title = re.search(r'class="title color-primary">\s*(?:<a[^>]*>)?\s*([^<]*?)\s*<', chunk)
        pub = re.search(r'<span class="">([^<]*)</span>', chunk)
        year = re.search(r"&nbsp;[^\d]*(\d{4})", chunk)
        if link and title and pub and year:
            out.append((link.group(1), html.unescape(title.group(1)), html.unescape(pub.group(1)), int(year.group(1))))
    if not out:
        raise RuntimeError("no series found on the creator page")
    return out


def load_ticks(ticks_file):
    """The calendar's done-map {key: ms}, or None when it can't be read."""
    try:
        if ticks_file:
            raw = open(ticks_file, encoding="utf-8").read()
        else:
            npx = shutil.which("npx") or shutil.which("npx.cmd")
            if not npx:
                raise RuntimeError("npx not found")
            tmp = os.path.join(tempfile.mkdtemp(), "ticks.json")
            r = subprocess.run([npx, "--yes", "wrangler", "r2", "object", "get", TICKS_OBJECT, "--remote", "--file", tmp],
                               capture_output=True, text=True, encoding="utf-8", errors="replace", cwd=ROOT, timeout=180)
            if r.returncode:
                raise RuntimeError("wrangler: " + (r.stderr or r.stdout).strip()[-300:])
            raw = open(tmp, encoding="utf-8").read()
        done = json.loads(raw).get("done", {})
        return done if isinstance(done, dict) else {}
    except Exception as e:
        print(f"WARN could not read ticks ({e}); got-it state not updated this run", file=sys.stderr)
        return None


def load_json(path, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        return default


def write_json(path, doc):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=2, ensure_ascii=False)
        f.write("\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="fetch and report, write nothing")
    ap.add_argument("--ticks-file", help="read ticks from this local file instead of R2")
    ap.add_argument("--summary", help="write the change summary here (used as the commit body)")
    ap.add_argument("--no-discover", action="store_true")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")

    cfg = load_json(CONFIG, None)
    state = load_json(STATE, {"got": {}, "seen": {}})
    got, seen = state.setdefault("got", {}), state.setdefault("seen", {})
    first_day = date.fromisoformat(cfg["first_day"])
    today = date.today()
    changes, errors = [], []

    # Previous reminders, to fall back on when a series page can't be read.
    old_doc = load_json(OUT, {"todos": []})
    old_by_series = {}
    for t in old_doc.get("todos", []):
        m = TITLE.match(t.get("title", ""))
        if m:
            old_by_series.setdefault((m.group(3), m.group(1)), []).append((m.group(2), t["date"]))

    # 1. Ticked reminders become "got".
    ticks = load_ticks(args.ticks_file)
    for key in (ticks or {}):
        if not key.startswith("C:") or "|" not in key:
            continue
        m = TITLE.match(key.split("|", 1)[1])
        if m:
            k = f"{m.group(3)}|{m.group(1)}|{m.group(2)}"
            if k not in got:
                got[k] = today.isoformat()
                changes.append(f"got: {m.group(1)} #{m.group(2)}")

    # 2-3. Fetch the series and build the reminders.
    reminders = []  # (date, list, title)
    blocked = False
    for rlist, series in cfg["lists"].items():
        for s in series:
            name = s["name"]
            issues, fresh = None, False
            if not blocked:
                try:
                    issues, fresh = series_issues(s["path"]), True
                except Blocked as e:
                    blocked = True
                    errors.append(f"BLOCKED {e}; not fetching anything else this run")
                except Exception as e:
                    errors.append(f"ERROR {name}: {e}")
            if not fresh:  # keep what the calendar had for this series
                for num, d in old_by_series.get((rlist, name), []):
                    reminders.append((d, rlist, f"Comics: {name} #{num} → {rlist} list"))
                continue
            listed = set()
            for title, rel in issues:
                m = ISSUE_TITLE.match(title)
                if not m:
                    if rel is None or rel >= first_day:
                        print(f"  CHECK {title} ({rel or 'TBD'}): not a numbered issue, not tracked")
                    continue
                num = m.group(2)
                k = f"{rlist}|{name}|{num}"
                listed.add(k)
                if rel is not None and rel >= first_day:
                    if k not in seen:
                        changes.append(f"new: {name} #{num} {rel:%b} {rel.day}")
                    elif seen[k] != rel.isoformat():
                        changes.append(f"redated: {name} #{num} {seen[k]} -> {rel.isoformat()}")
                if rel is not None:
                    seen[k] = rel.isoformat()
                elif k in seen:
                    changes.append(f"undated: {name} #{num} (was {seen[k]})")
                    del seen[k]
                if rel is not None and rel >= first_day and k not in got:
                    reminders.append((rel.isoformat(), rlist, f"Comics: {name} #{num} → {rlist} list"))
            prefix = f"{rlist}|{name}|"
            for k in [k for k in seen if k.startswith(prefix) and k not in listed]:
                if date.fromisoformat(seen[k]) >= today and k not in got:
                    changes.append(f"dropped: {name} #{k[len(prefix):]} (was {seen[k]})")
                del seen[k]

    # 4. Creators: series nobody follows yet.
    found = []
    if not args.no_discover:
        tracked = {s["path"].split("/")[0] for series in cfg["lists"].values() for s in series}
        skip = tracked | set(cfg.get("ignore", []))
        for c in cfg.get("creators", []):
            if blocked:
                break
            try:
                for path, title, pub, year in creator_series(c["path"]):
                    if path.split("/")[0] in skip or year < c.get("since", 0):
                        continue
                    if c.get("publisher") and pub != c["publisher"]:
                        continue
                    found.append((c["name"], title, pub, year, path))
            except Blocked as e:
                blocked = True
                errors.append(f"BLOCKED {e}")
            except Exception as e:
                errors.append(f"ERROR creator {c['name']}: {e}")

    todos = [{"title": t, "date": d} for d, _, t in sorted(reminders, key=lambda r: (r[0], r[1]))]
    if args.dry_run:
        print("dry run: nothing written")
    else:
        write_json(OUT, {"note": NOTE, "generated": today.isoformat(), "todos": todos})
        write_json(STATE, state)
        if not args.no_discover and found:
            lines = ["# Comic tracker: series to consider following\n",
                     "Found on a followed creator's League of Comic Geeks page, not in `series.json` (followed or ignored). "
                     "Add one to a list in `series.json` to follow it, or add its id to `ignore`.\n"]
            for who, title, pub, year, path in found:
                lines.append(f"- **{title}** ({pub}, {year}): {who}. `{path}` https://leagueofcomicgeeks.com/comics/series/{path}")
            with open(DISCOVERIES, "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(lines) + "\n")
        elif os.path.exists(DISCOVERIES) and not found and not args.no_discover and not blocked:
            os.remove(DISCOVERIES)

    for t in todos:
        print(t["date"], t["title"])
    print(f"{len(todos)} reminders")
    for c in changes:
        print("  change:", c)
    for who, title, pub, year, path in found:
        print(f"  DISCOVER {title} ({pub}, {year}) {path}  <- {who}")
    for e in errors:
        print(e, file=sys.stderr)
    if args.summary and not args.dry_run:
        with open(args.summary, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(changes) + "\n")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
